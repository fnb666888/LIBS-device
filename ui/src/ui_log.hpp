#pragma once

// UI 落盘日志（`ui/src/ui_log.hpp`）。
//
// **为什么必须有这个文件**：2026-10-07 现场反复出现"按了出光测量之后界面完全
// 消失、过一会儿又被计划任务拉回来"。查这个的时候**一条日志都没有** ——
// 界面上那个"系统消息"面板只活在内存里，进程一死就全没了，
// 只能靠外部进程信息和计划任务的退出码反推。
//
// 一个会自己消失的进程必须留下证据。所以从起手、窗口关闭、轮询线程的启停，
// 到每一条界面消息，全部追加落盘。
//
// 纪律：
//   * **逐行 flush**（每行 open/append/close）。崩在下一行之前也要留下上一行 ——
//     带缓冲的日志恰恰在最需要它的那一刻丢数据。
//   * 写日志失败**绝不能**让界面出事：拿不到文件就静默跳过，不抛、不弹窗。
//   * 跨线程安全：UI 线程与两个轮询线程都会写。
//
// 文件位置：可执行文件同目录下的 ui.log；环境变量 LIBS_UI_LOG 可覆盖。

#include <QString>

namespace libs::ui {

// 追加一行。level 用 "INFO" / "WARN" / "ERROR" / "EXIT" 这类短标签。
void ui_log(const char* level, const QString& message);

// 实际使用的日志路径（首次调用时解析）。
QString ui_log_path();

}  // namespace libs::ui
